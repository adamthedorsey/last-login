type Px = [x: number, y: number, w: number, h: number, fill: string];

function px(list: Px[]) {
  return list.map(([x, y, w, h, fill], i) => (
    <rect key={i} x={x} y={y} width={w} height={h} fill={fill} />
  ));
}

